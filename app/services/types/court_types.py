"""Типы судов СУДРФ: коды, русские названия и порядок вывода.

Единый источник правды для всех мест, где фигурируют коды типов судов
(генерация PDF-отчёта, сортировка списка судов в SudrfClient).
"""

# Порядок ключей задаёт и порядок сортировки, и словарь меток
# (dict сохраняет порядок вставки — Python 3.7+).
COURT_TYPES = {
    "MS": "Судебный участок",
    "RS": "Районный суд",
    "OS": "Областной суд",
    "AJ": "Апелляционный суд",
    "KJ": "Кассационный суд",
    "GV": "Гарнизонный военный суд",
    "OV": "Окружной военный суд",
    "AV": "Апелляционный военный суд",
    "KV": "Кассационный военный суд",
    "VS": "Верховный суд",
}

# Порядок вывода (производная величина; список кодов не дублируется вручную).
COURT_TYPE_ORDER = tuple(COURT_TYPES)

DEFAULT_COURT_LABEL = "Суд"


def court_type_label(code: str) -> str:
    """Русское название типа суда; fallback — сам код, затем 'Суд'."""
    return COURT_TYPES.get(code, code or DEFAULT_COURT_LABEL)
